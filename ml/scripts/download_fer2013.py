from pathlib import Path

def check_fer2013_status():
    dataset_dir = Path(__file__).resolve().parent.parent / "datasets" / "fer2013"
    train_dir = dataset_dir / "train"
    test_dir = dataset_dir / "test"
    manifest = dataset_dir / "fer2013_manifest.csv"
    
    print("FER-2013 Status Check:")
    print(f"  Dataset directory: {dataset_dir.exists()}")
    print(f"  Train folder exists: {train_dir.exists()}")
    print(f"  Test folder exists: {test_dir.exists()}")
    print(f"  Manifest exists: {manifest.exists()}")

if __name__ == "__main__":
    check_fer2013_status()

